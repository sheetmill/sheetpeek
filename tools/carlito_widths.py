r"""Write ``src/sheetpeek/_carlito.py``: Carlito's advance widths, a small table of numbers.

    uv run --with fonttools python tools/carlito_widths.py \\
        --regular Carlito-Regular.ttf --bold Carlito-Bold.ttf \\
        --italic Carlito-Italic.ttf --bold-italic Carlito-BoldItalic.ttf

Carlito (SIL Open Font License 1.1, https://github.com/googlefonts/carlito) is metric-compatible
with Calibri. The HTML backend spaces Calibri text from these widths so that a browser draws it
as wide as Excel for Mac does (``ARCHITECTURE.md`` §7.3). The font files are read here only and
never committed; the package holds the numbers alone. fontTools is needed only to run this.
"""

from __future__ import annotations

import argparse
import textwrap
from pathlib import Path

from fontTools.ttLib import TTFont

OUTPUT = Path(__file__).resolve().parents[1] / "src" / "sheetpeek" / "_carlito.py"
FIRST, LAST = 32, 126  # printable ASCII: the characters xlformat measures
STYLES = {"regular": "regular", "bold": "bold", "italic": "italic", "bold_italic": "bold italic"}

HEADER = '''"""Carlito's advance widths, for spacing Calibri text in HTML as Excel for Mac does.

Generated by ``tools/carlito_widths.py`` from Carlito {version} (Copyright 2013 The Carlito
Project Authors, https://github.com/googlefonts/carlito), which is licensed under the SIL Open
Font License 1.1. Carlito is metric-compatible with Calibri. Only the advance widths are kept,
in font units, for printable ASCII; no font data is included.
"""

UNITS_PER_EM = {units}
FIRST = {first}  # the advance of chr(FIRST + k) is ADVANCES[style][k]

# fmt: off
ADVANCES: dict[str, tuple[int, ...]] = {{
'''


def advances(path: Path) -> tuple[int, list[int], str]:
    """Units per em, the advances of printable ASCII, and the font's version string."""
    font = TTFont(path)
    cmap, metrics = font.getBestCmap(), font["hmtx"]
    widths = [metrics[cmap[code]][0] for code in range(FIRST, LAST + 1)]
    version = font["name"].getDebugName(5) or "unknown"
    return font["head"].unitsPerEm, widths, version.removeprefix("Version ")


def main() -> None:
    """Read the four styles and write the module."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    for option in STYLES:
        parser.add_argument(f"--{option.replace('_', '-')}", type=Path, required=True)
    args = parser.parse_args()
    tables, units, version = {}, None, None
    for option, style in STYLES.items():
        units, tables[style], version = advances(getattr(args, option))
    lines = [HEADER.format(version=version, units=units, first=FIRST)]
    for style, widths in tables.items():
        body = textwrap.wrap(", ".join(map(str, widths)) + ",", 92)
        rows = "".join(f"        {line}\n" for line in body)
        lines.append(f'    "{style}": (\n{rows}    ),\n')
    lines.append("}\n# fmt: on\n")
    OUTPUT.write_text("".join(lines), encoding="utf-8")
    print(f"wrote {OUTPUT}")


if __name__ == "__main__":
    main()
